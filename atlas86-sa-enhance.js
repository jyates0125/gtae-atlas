/* Approved Team Jura SA map-art enhancement.
 * A remotely served credited map image is a geographic background, NOT proof of individual locations.
 * User imported map art and location packs continue to override this reference image.
 */
(()=>{'use strict';
const URL='https://raw.githubusercontent.com/gptrk0/mtasa-map-images/master/default/map_default_2048.jpg';
function init(){
 const bg=document.getElementById('mapBackground'),status=document.getElementById('mapStatus'),side=document.querySelector('.sidepanel');
 if(!bg)return;
 const image=document.createElement('img');image.src=URL;image.alt='GTA San Andreas in-game map reference, generated by Patrick / gptrk0, sourced from MIT-licensed map images project';image.decoding='async';image.loading='eager';image.className='j86-san-map';
 image.addEventListener('load',()=>{if(!bg.contains(image))return;bg.classList.add('j86-map-loaded');if(status)status.textContent='San Andreas map artwork · gptrk0 / MTA:SA · 2048 px · source attributed · no unsourced pins';});
 image.addEventListener('error',()=>{if(!bg.contains(image))return;image.remove();if(status)status.textContent='Reference map unavailable. Import your own map image to continue.';});
 bg.replaceChildren(image);
 const credit=document.createElement('p');credit.className='j86-sa-credit';
 credit.append('Map art: ');const link=document.createElement('a');link.href='https://github.com/gptrk0/mtasa-map-images';link.target='_blank';link.rel='noopener noreferrer';link.textContent='Patrick / MTA:SA map images (MIT repository)';credit.append(link,'. In-game imagery remains © its rights holders. Collection positions are not inferred from this picture.');
 const credits=document.querySelector('.credits');if(credits)credits.append(credit);
}
if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',init,{once:true});else init();
})();
