from pathlib import Path
from playwright.sync_api import sync_playwright
import subprocess,time,json,sys
root=Path(__file__).resolve().parents[1]
proc=subprocess.Popen(['python','-m','http.server','8765','--bind','127.0.0.1'],cwd=str(root),stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
results=[]
def check(name,pass_value,note=''):
 results.append({'test':name,'passed':bool(pass_value),'note':note})
 try:
  assert pass_value, name+' '+note
 except AssertionError as e:print('FAIL:',e)
try:
 time.sleep(0.7)
 with sync_playwright() as p:
  browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
  pg=browser.new_page(viewport={'width':1440,'height':900},accept_downloads=True)
  errs=[];pg.on('pageerror',lambda e:errs.append(str(e)))
  pg.goto('http://127.0.0.1:8765/atlas81-hq.html',wait_until='domcontentloaded')
  pg.locator('#selectedTitle').wait_for(state='attached')
  pg.wait_for_timeout(500)
  check('Homepage heading',pg.locator('h1').first.inner_text().find('YOUR WORLD')>=0)
  check('Collection manifest loads',pg.locator('#statSets').inner_text()=='20',pg.locator('#statSets').inner_text())
  check('Heist links populated',pg.locator('#heistTiles a').count()==15)
  pg.screenshot(path=str(root/'tests/desktop-home.png'),full_page=True)
  pg.locator('.mainnav a[data-view="collections"]').click();pg.wait_for_timeout(100)
  check('Collectibles view shows',pg.locator('#collections').is_visible())
  check('Story set selector',pg.locator('#setList button').count()==11)
  pg.locator('#modeOnline').click();pg.wait_for_timeout(80)
  check('Online set selector',pg.locator('#setList button').count()==9)
  pg.locator('#setSearch').fill('Playing Cards');pg.wait_for_timeout(80)
  check('Search sets narrows',pg.locator('#setList button').count()==1)
  pg.locator('#setList button').first.click()
  check('Playing cards renders 54',pg.locator('#itemGrid article').count()==54)
  pg.locator('#itemGrid input[type=checkbox]').first.check();pg.wait_for_timeout(90)
  check('Completion updates',pg.locator('#selectedCount').inner_text()=='1 / 54')
  pg.locator('#itemGrid textarea').first.fill('Near Sonar Dock');pg.locator('#itemGrid textarea').first.blur();pg.wait_for_timeout(70)
  check('Note saved',pg.evaluate("JSON.parse(localStorage.getItem('team-jura-atlas81-hq-v1')).items['online-playing-cards:1'].note")=='Near Sonar Dock')
  pg.reload(wait_until='domcontentloaded');pg.wait_for_timeout(300)
  pg.locator('.mainnav a[data-view="collections"]').click();pg.locator('#modeOnline').click();pg.locator('#setSearch').fill('Playing Cards');pg.locator('#setList button').first.click()
  check('Local progress retained on refresh',pg.locator('#selectedCount').inner_text()=='1 / 54')
  pg.locator('#selectUndone').click();pg.wait_for_timeout(90)
  check('Queue incomplete only',pg.locator('#collQueue').inner_text()=='53')
  with pg.expect_download() as d: pg.locator('#exportAll').click()
  check('Backup downloads',d.value.suggested_filename.endswith('.json'))
  pg.screenshot(path=str(root/'tests/desktop-collectibles.png'),full_page=False)
  check('No uncaught JS errors',not errs,str(errs))
  mobile=browser.new_page(viewport={'width':390,'height':844},device_scale_factor=1)
  mobile.goto('http://127.0.0.1:8765/atlas81-hq.html',wait_until='domcontentloaded');mobile.wait_for_timeout(350)
  mobile.locator('#menu').click()
  check('Mobile menu opens',mobile.locator('#nav').evaluate('(e)=>e.classList.contains("open")'))
  mobile.locator('#nav a[data-view="collections"]').click();mobile.wait_for_timeout(140)
  check('Mobile navigation works',mobile.locator('#collections').is_visible())
  check('No horizontal page overflow',mobile.evaluate('document.documentElement.scrollWidth<=window.innerWidth+2'),str(mobile.evaluate('document.documentElement.scrollWidth')))
  mobile.screenshot(path=str(root/'tests/mobile-collectibles.png'),full_page=False)
  browser.close()
finally:proc.terminate()
(root/'tests/qa-results.json').write_text(json.dumps({'passed':sum(r['passed'] for r in results),'total':len(results),'results':results},indent=2))
print(json.dumps({'passed':sum(r['passed'] for r in results),'total':len(results),'results':results},indent=2))
if not all(r['passed'] for r in results):sys.exit(1)
